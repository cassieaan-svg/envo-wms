INSERT INTO commodities (name, category, unit, is_active)
SELECT i.name, i.category, i.unit, i.is_active
  FROM _catalogue_import i
 WHERE NOT EXISTS (
   SELECT 1 FROM commodities c WHERE lower(trim(c.name)) = lower(trim(i.name))
 );

-- Only commodities that came in with no price at all get one here — an existing commodity's
-- price (however it got one) is never touched or superseded by the imported figure.
INSERT INTO commodity_prices (commodity_id, unit_price, is_current)
SELECT c.id, i.unit_price, TRUE
  FROM _catalogue_import i
  JOIN commodities c ON lower(trim(c.name)) = lower(trim(i.name))
 WHERE i.unit_price IS NOT NULL
   AND NOT EXISTS (
     SELECT 1 FROM commodity_prices p WHERE p.commodity_id = c.id AND p.is_current
   );

